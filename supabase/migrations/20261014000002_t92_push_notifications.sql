-- ============================================================================
-- T9.2 (2/3): push notifications (Expo Push Service).
--
-- Model:
--   * notifications (existing) stays the ONE notification domain: every
--     logical notification is a row there (idempotency_key unique). Nothing in
--     the workflow functions changes.
--   * A trigger copies push-worthy notifications into push_outbox (one row per
--     notification: notification_id is unique, so a retried domain event can
--     never queue a second push). Which types are pushed is decided ONLY by
--     pw_push_eligible(): REPORT_VERIFIED, REPORT_REJECTED (citizen) and
--     CASE_ASSIGNED (officer). The four "closed without a citizen decision"
--     outcomes create no citizen notification, so they can never be pushed.
--   * A trusted sender (Edge Function push-dispatch, service role) claims due
--     outbox rows, sends them to the recipient's enabled devices and records
--     the result. Push text is built by the sender from the type only
--     (generic lock-screen wording; no evidence, location, identity, plate).
--   * push_devices holds Expo push tokens. Clients have NO table access at all
--     (not even to their own rows): they register/unregister through two
--     functions bound to auth.uid(). Supervisors/console cannot read tokens.
--   * Push is an enhancement: the enqueue trigger swallows its own errors, so
--     a push problem can never fail report submission, assignment or case
--     completion.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Devices

create table public.push_devices (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  -- Random id generated by the app on first launch (not an advertising or hardware id).
  installation_id text not null check (installation_id ~ '^[A-Za-z0-9_-]{8,100}$'),
  expo_push_token text not null check (expo_push_token ~ '^Expo(nent)?PushToken\[[A-Za-z0-9_-]{8,200}\]$'),
  platform text not null check (platform in ('ios', 'android')),
  enabled boolean not null default true,
  disabled_reason text check (disabled_reason in ('SIGNED_OUT', 'DEVICE_NOT_REGISTERED', 'REPLACED', 'MOVED_TO_OTHER_ACCOUNT')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique (user_id, installation_id),
  check (enabled = (disabled_reason is null))
);
-- A token (and an installation) delivers for at most one account at a time.
create unique index push_devices_one_active_token on public.push_devices (expo_push_token) where enabled;
create unique index push_devices_one_active_installation on public.push_devices (installation_id) where enabled;
create index push_devices_user_idx on public.push_devices (user_id) where enabled;
create trigger push_devices_updated_at before update on public.push_devices for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Outbox (one row per pushed notification) and per-device tickets

create table public.push_outbox (
  id uuid primary key default gen_random_uuid(),
  notification_id uuid not null unique references public.notifications (id) on delete cascade,
  recipient_id uuid not null references public.profiles (id) on delete cascade,
  status text not null default 'PENDING' check (status in ('PENDING', 'SENDING', 'SENT', 'NO_DEVICE', 'FAILED')),
  attempts integer not null default 0 check (attempts between 0 and 100),
  next_attempt_at timestamptz not null default now(),
  locked_until timestamptz,
  -- A short code only (never a raw provider response).
  last_error text check (last_error ~ '^[A-Za-z][A-Za-z0-9_]{1,39}$'),
  -- A push more than a day late is worse than none.
  expires_at timestamptz not null default now() + interval '24 hours',
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index push_outbox_due_idx on public.push_outbox (next_attempt_at) where status in ('PENDING', 'SENDING');
create trigger push_outbox_updated_at before update on public.push_outbox for each row execute function public.set_updated_at();

-- One delivery per (notification, device): a retry only sends to devices that
-- have no ticket yet, so a partial failure never double-sends.
create table public.push_tickets (
  id uuid primary key default gen_random_uuid(),
  outbox_id uuid not null references public.push_outbox (id) on delete cascade,
  device_id uuid not null references public.push_devices (id) on delete cascade,
  ticket_id text check (ticket_id ~ '^[A-Za-z0-9_-]{1,100}$'),
  status text not null check (status in ('OK', 'ERROR')),
  error text check (error ~ '^[A-Za-z][A-Za-z0-9_]{1,39}$'),
  receipt_status text check (receipt_status in ('OK', 'ERROR')),
  receipt_error text check (receipt_error ~ '^[A-Za-z][A-Za-z0-9_]{1,39}$'),
  created_at timestamptz not null default now(),
  checked_at timestamptz,
  unique (outbox_id, device_id),
  check ((status = 'OK') = (ticket_id is not null))
);
create unique index push_tickets_ticket_idx on public.push_tickets (ticket_id) where ticket_id is not null;

-- No client access at all (RLS on, no policies, no privileges).
alter table public.push_devices enable row level security;
alter table public.push_outbox enable row level security;
alter table public.push_tickets enable row level security;
revoke all on public.push_devices, public.push_outbox, public.push_tickets from anon, authenticated;
grant select, insert, update, delete on public.push_devices, public.push_outbox, public.push_tickets to service_role;

-- ---------------------------------------------------------------------------
-- Which notifications are pushed (the ONE place)

create function public.pw_push_eligible(p_type public.notification_type) returns boolean
language plpgsql immutable set search_path = '' as $$
begin
  return p_type::text in ('REPORT_VERIFIED', 'REPORT_REJECTED', 'CASE_ASSIGNED');
end $$;

create function public.pw_enqueue_push() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if public.pw_push_eligible(new.type) and new.recipient_role in ('CITIZEN', 'OFFICER') then
    begin
      insert into public.push_outbox (notification_id, recipient_id) values (new.id, new.recipient_id)
      on conflict (notification_id) do nothing;
    exception when others then
      -- Push is an enhancement: never fail the workflow transaction because of it.
      raise warning 'push enqueue skipped (%)', sqlstate;
    end;
  end if;
  return new;
end $$;
create trigger notifications_enqueue_push after insert on public.notifications
  for each row execute function public.pw_enqueue_push();

-- ---------------------------------------------------------------------------
-- Device registration (signed-in citizen/officer, own device only)

create function public.register_push_device(p_installation_id text, p_expo_push_token text, p_platform text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  me uuid := public.pw_require_user();
  existing public.push_devices;
  changed boolean := true;
begin
  if not exists (select 1 from public.profiles p where p.id = me and p.role in ('CITIZEN', 'OFFICER')) then
    perform public.pw_fail('FORBIDDEN', 'Push notifications are available for citizen and officer accounts.');
  end if;
  if coalesce(p_installation_id, '') !~ '^[A-Za-z0-9_-]{8,100}$' then perform public.pw_fail('INVALID_INPUT', 'Invalid installation id.'); end if;
  if coalesce(p_expo_push_token, '') !~ '^Expo(nent)?PushToken\[[A-Za-z0-9_-]{8,200}\]$' then perform public.pw_fail('INVALID_INPUT', 'Invalid push token.'); end if;
  if coalesce(p_platform, '') not in ('ios', 'android') then perform public.pw_fail('INVALID_INPUT', 'Invalid platform.'); end if;

  -- Serialize concurrent registrations of the same device / token.
  perform pg_advisory_xact_lock(hashtext('pw_push_installation:' || p_installation_id));
  perform pg_advisory_xact_lock(hashtext('pw_push_token:' || p_expo_push_token));

  -- This device now belongs to the caller: another account's registration on
  -- it (e.g. a sign-out that could not reach the server) stops receiving here.
  update public.push_devices set enabled = false, disabled_reason = 'MOVED_TO_OTHER_ACCOUNT'
  where enabled and user_id <> me and (expo_push_token = p_expo_push_token or installation_id = p_installation_id);
  -- The same account re-registered the token under a new installation (reinstall).
  update public.push_devices set enabled = false, disabled_reason = 'REPLACED'
  where enabled and user_id = me and installation_id <> p_installation_id and expo_push_token = p_expo_push_token;

  select * into existing from public.push_devices d where d.user_id = me and d.installation_id = p_installation_id for update;
  if found then
    changed := not existing.enabled or existing.expo_push_token <> p_expo_push_token or existing.platform <> p_platform;
    update public.push_devices
      set expo_push_token = p_expo_push_token, platform = p_platform, enabled = true, disabled_reason = null, last_seen_at = now()
      where id = existing.id;
  else
    insert into public.push_devices (user_id, installation_id, expo_push_token, platform)
    values (me, p_installation_id, p_expo_push_token, p_platform);
  end if;
  return jsonb_build_object('registered', true, 'changed', changed);
end $$;

-- Sign-out (or "turn off on this device"): only the caller's own registration.
create function public.unregister_push_device(p_installation_id text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  me uuid := public.pw_require_user();
  n integer;
begin
  if coalesce(p_installation_id, '') !~ '^[A-Za-z0-9_-]{8,100}$' then perform public.pw_fail('INVALID_INPUT', 'Invalid installation id.'); end if;
  update public.push_devices set enabled = false, disabled_reason = 'SIGNED_OUT'
  where user_id = me and installation_id = p_installation_id and enabled;
  get diagnostics n = row_count;
  return jsonb_build_object('unregistered', n > 0);
end $$;

-- ---------------------------------------------------------------------------
-- Trusted sender API (service role only; the Edge Function push-dispatch)

create function public.push_claim_batch(p_limit integer default 50, p_lease_seconds integer default 120) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  lim integer := least(greatest(coalesce(p_limit, 50), 1), 100);
  lease interval := make_interval(secs => least(greatest(coalesce(p_lease_seconds, 120), 10), 600));
  result jsonb;
begin
  update public.push_outbox set status = 'FAILED', last_error = 'EXPIRED', locked_until = null
  where status in ('PENDING', 'SENDING') and expires_at <= now();

  with due as (
    select o.id from public.push_outbox o
    where o.status in ('PENDING', 'SENDING') and o.next_attempt_at <= now()
      and (o.locked_until is null or o.locked_until <= now())
    order by o.next_attempt_at, o.id
    limit lim
    for update skip locked
  ), claimed as (
    update public.push_outbox o set status = 'SENDING', locked_until = now() + lease, attempts = o.attempts + 1
    from due where o.id = due.id
    returning o.id, o.notification_id, o.recipient_id, o.attempts
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'outbox_id', c.id,
    'attempt', c.attempts,
    'notification', jsonb_build_object(
      'id', n.id, 'type', n.type, 'recipient_role', n.recipient_role, 'amount_cents', n.amount_cents,
      'report_number', r.public_report_number, 'case_id', n.case_id),
    'devices', coalesce((
      select jsonb_agg(jsonb_build_object('device_id', d.id, 'token', d.expo_push_token, 'platform', d.platform) order by d.created_at, d.id)
      from public.push_devices d
      where d.user_id = c.recipient_id and d.enabled
        and not exists (select 1 from public.push_tickets t where t.outbox_id = c.id and t.device_id = d.id)), '[]'::jsonb)
  ) order by c.id), '[]'::jsonb)
  into result
  from claimed c
  join public.notifications n on n.id = c.notification_id
  left join public.reports r on r.id = n.report_id;
  return result;
end $$;

-- Record one send attempt. p_tickets: [{device_id, status: 'ok'|'error', ticket_id?, error?}] in
-- any order; p_request_error: a short code when the whole request failed (no tickets).
-- Classification lives here: DeviceNotRegistered (or a token the sender found malformed, InvalidToken) disables the device; MessageRateExceeded
-- is retried; other per-device errors are final for this notification on that device.
create function public.push_record_result(p_outbox_id uuid, p_tickets jsonb default '[]'::jsonb, p_request_error text default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  o public.push_outbox;
  t jsonb;
  dev uuid;
  err text;
  remaining integer;
  delivered integer;
  max_attempts constant integer := 5;
  req_err text := case when p_request_error ~ '^[A-Za-z][A-Za-z0-9_]{1,39}$' then p_request_error end;
  permanent_request boolean := p_request_error in ('UNAUTHORIZED', 'BAD_REQUEST', 'PUSH_TOO_MANY_EXPERIENCE_IDS', 'NOT_CONFIGURED');
begin
  select * into o from public.push_outbox x where x.id = p_outbox_id for update;
  if not found or o.status <> 'SENDING' then return jsonb_build_object('status', coalesce(o.status, 'MISSING'), 'ignored', true); end if;

  for t in select * from jsonb_array_elements(case when jsonb_typeof(p_tickets) = 'array' then p_tickets else '[]'::jsonb end) loop
    dev := public.try_uuid(t ->> 'device_id');
    -- Only the recipient's own devices.
    continue when dev is null or not exists (select 1 from public.push_devices d where d.id = dev and d.user_id = o.recipient_id);
    err := case when (t ->> 'error') ~ '^[A-Za-z][A-Za-z0-9_]{1,39}$' then t ->> 'error' end;
    if t ->> 'status' = 'ok' and (t ->> 'ticket_id') ~ '^[A-Za-z0-9_-]{1,100}$' then
      insert into public.push_tickets (outbox_id, device_id, ticket_id, status) values (o.id, dev, t ->> 'ticket_id', 'OK')
      on conflict do nothing;
    elsif err = 'MessageRateExceeded' then
      null; -- transient: no ticket, the device is tried again on the next attempt
    else
      insert into public.push_tickets (outbox_id, device_id, status, error) values (o.id, dev, 'ERROR', coalesce(err, 'UnknownError'))
      on conflict do nothing;
      if err in ('DeviceNotRegistered', 'InvalidToken') then
        update public.push_devices set enabled = false, disabled_reason = 'DEVICE_NOT_REGISTERED' where id = dev and enabled;
      end if;
    end if;
  end loop;

  select count(*) into remaining from public.push_devices d
  where d.user_id = o.recipient_id and d.enabled
    and not exists (select 1 from public.push_tickets x where x.outbox_id = o.id and x.device_id = d.id);
  select count(*) into delivered from public.push_tickets x where x.outbox_id = o.id and x.status = 'OK';

  if req_err is null and remaining = 0 then
    update public.push_outbox
      set status = case when delivered > 0 then 'SENT' when exists (select 1 from public.push_tickets x where x.outbox_id = o.id) then 'FAILED' else 'NO_DEVICE' end,
          sent_at = case when delivered > 0 then now() end,
          last_error = case when delivered > 0 then null else (select x.error from public.push_tickets x where x.outbox_id = o.id and x.error is not null limit 1) end,
          locked_until = null
      where id = o.id
      returning status into err;
  elsif permanent_request or o.attempts >= max_attempts then
    update public.push_outbox set status = 'FAILED', last_error = coalesce(req_err, 'RETRIES_EXHAUSTED'), locked_until = null
      where id = o.id returning status into err;
  else
    -- Exponential backoff: 30 s, 1 min, 2 min, 4 min (capped at 30 min).
    update public.push_outbox
      set status = 'PENDING', last_error = coalesce(req_err, 'PARTIAL_DELIVERY'), locked_until = null,
          next_attempt_at = now() + least(make_interval(secs => 30 * power(2, greatest(o.attempts - 1, 0))::integer), interval '30 minutes')
      where id = o.id returning status into err;
  end if;
  return jsonb_build_object('status', err);
end $$;

-- Tickets whose receipt should now be available (>= 15 min old, < 23 h old, not checked yet).
create function public.push_pending_receipts(p_limit integer default 300) returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(x.ticket_id), '[]'::jsonb) from (
    select t.ticket_id from public.push_tickets t
    where t.status = 'OK' and t.checked_at is null
      and t.created_at <= now() - interval '15 minutes' and t.created_at > now() - interval '23 hours'
    order by t.created_at
    limit least(greatest(coalesce(p_limit, 300), 1), 1000)
  ) x;
$$;

-- p_receipts: [{ticket_id, status: 'ok'|'error', error?}]. DeviceNotRegistered disables the device.
create function public.push_record_receipts(p_receipts jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  rc jsonb;
  err text;
  n integer := 0;
  dev uuid;
begin
  for rc in select * from jsonb_array_elements(case when jsonb_typeof(p_receipts) = 'array' then p_receipts else '[]'::jsonb end) loop
    err := case when (rc ->> 'error') ~ '^[A-Za-z][A-Za-z0-9_]{1,39}$' then rc ->> 'error' end;
    update public.push_tickets
      set receipt_status = case when rc ->> 'status' = 'ok' then 'OK' else 'ERROR' end,
          receipt_error = case when rc ->> 'status' = 'ok' then null else coalesce(err, 'UnknownError') end,
          checked_at = now()
      where ticket_id = rc ->> 'ticket_id' and checked_at is null
      returning device_id into dev;
    if found then
      n := n + 1;
      if err = 'DeviceNotRegistered' then
        update public.push_devices set enabled = false, disabled_reason = 'DEVICE_NOT_REGISTERED' where id = dev and enabled;
      end if;
    end if;
  end loop;
  return jsonb_build_object('recorded', n);
end $$;

