-- Privileges

revoke all on function public.pw_push_eligible(public.notification_type), public.pw_enqueue_push() from public, anon, authenticated;

revoke all on function public.register_push_device(text, text, text), public.unregister_push_device(text) from public, anon;
grant execute on function public.register_push_device(text, text, text), public.unregister_push_device(text) to authenticated;

-- The sender API is NOT client API: service role only.
revoke all on function
  public.push_claim_batch(integer, integer), public.push_record_result(uuid, jsonb, text),
  public.push_pending_receipts(integer), public.push_record_receipts(jsonb)
from public, anon, authenticated;
grant execute on function
  public.push_claim_batch(integer, integer), public.push_record_result(uuid, jsonb, text),
  public.push_pending_receipts(integer), public.push_record_receipts(jsonb)
to service_role;
